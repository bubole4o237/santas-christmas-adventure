/**
 * Дефиниции на шестте нива. Всички координати са в пиксели (y расте надолу).
 * Нормалният скок достига ~150px височина и ~220px дължина при пълна скорост,
 * затова пропастите са до ~170px, а стъпалата – до ~120px.
 */

const ground = (x, w, y, type = 'snow', h = 700) => ({ x, y, w, h, type });
const row = (type, x0, y, n, dx = 40) => Array.from({ length: n }, (_, i) => ({ type, x: x0 + i * dx, y }));

/**
 * Поредица от магически платформи. Всяка се появява `step` секунди след предходната,
 * така че винаги има момент, в който две съседни са видими едновременно.
 */
function magicSeq(list, period = 4, step = 1.2, on = 0.62) {
  return list.map(([x, y, w = 100], i) => ({
    x,
    y,
    w,
    period,
    on,
    phase: (((1 - (i * step) / period) % 1) + 1) % 1,
  }));
}

